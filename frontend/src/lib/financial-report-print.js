export const escapeHtml = (value) =>
  String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");

export const formatAmount = (value) => Number(value || 0).toLocaleString();

export function buildFinancialPrintDocument({
  hospitalName,
  title,
  periodLabel,
  summary = [],
  content,
}) {
  const generatedAt = new Date().toLocaleString();
  const summaryMarkup = summary
    .map(
      ({ label, value }) => `
        <div class="summary-item">
          <div class="summary-label">${escapeHtml(label)}</div>
          <div class="summary-value">${escapeHtml(value)}</div>
        </div>`,
    )
    .join("");

  return `
    <!DOCTYPE html>
    <html>
      <head>
        <title>${escapeHtml(title)} - ${escapeHtml(hospitalName)}</title>
        <style>
          @page{margin:16mm 14mm 18mm;size:A4}
          body{font-family:Arial,sans-serif;color:#172033;font-size:11px;line-height:1.45}
          .header{display:flex;justify-content:space-between;gap:20px;border-bottom:3px solid #173b63;padding-bottom:14px;margin-bottom:18px}
          .header h1{color:#173b63;font-size:21px;margin:0}.header h2{font-size:14px;letter-spacing:.4px;margin:4px 0 0}.header p{color:#526075;margin:3px 0}
          .report-meta{text-align:right;color:#526075}.report-meta strong{color:#172033}
          .summary{display:grid;grid-template-columns:repeat(${Math.min(Math.max(summary.length, 1), 3)},1fr);gap:8px;margin:14px 0 20px}.summary-item{border:1px solid #d9e1ea;border-top:3px solid #e87518;padding:9px}.summary-label{color:#526075;font-size:10px;text-transform:uppercase}.summary-value{color:#172033;font-size:15px;font-weight:bold;margin-top:3px}
          table{width:100%;border-collapse:collapse;margin:8px 0}th,td{padding:8px;border-bottom:1px solid #d9e1ea}th{background:#173b63;color:#fff;text-align:left;font-size:10px;text-transform:uppercase}.text-right{text-align:right}.category{font-weight:bold;text-align:left;background:#eef4fa}.subcategory{text-align:left;padding-left:20px}.section-total,.total-row{font-weight:bold;border-top:2px solid #173b63;background:#f8fafc}.net-income{font-size:13px;font-weight:bold;border-top:3px double #173b63;background:#edf7ef}
          .notice{border-left:3px solid #e87518;background:#fff7ed;color:#7c2d12;padding:8px 10px;margin-top:20px;font-size:10px}.footer{position:fixed;bottom:-11mm;left:0;right:0;border-top:1px solid #cbd5e1;color:#526075;padding-top:5px;font-size:9px}.footer .right{float:right}.page:after{content:counter(page)}
          @media print{table{break-inside:auto}tr{break-inside:avoid}}
        </style>
      </head>
      <body>
        <div class="header"><div><h1>${escapeHtml(hospitalName)}</h1><h2>${escapeHtml(title).toUpperCase()}</h2><p>Financial statement generated by MediCore HMS</p></div><div class="report-meta"><p><strong>Reporting period</strong><br>${escapeHtml(periodLabel)}</p><p><strong>Generated</strong><br>${escapeHtml(generatedAt)}</p></div></div>
        ${summaryMarkup ? `<div class="summary">${summaryMarkup}</div>` : ""}
        ${content}
        <div class="notice">Confidential financial information. Print, distribute, and retain this report only in accordance with your hospital's financial controls and records policy.</div>
        <div class="footer"><span>${escapeHtml(hospitalName)} | MediCore HMS</span><span class="right">Page <span class="page"></span></span></div>
      </body>
    </html>`;
}

export function printFinancialReport(documentContent) {
  const printWindow = window.open("", "_blank", "width=900,height=700");

  if (!printWindow) {
    return false;
  }

  printWindow.document.write(documentContent);
  printWindow.document.close();
  window.setTimeout(() => printWindow.print(), 300);
  return true;
}
